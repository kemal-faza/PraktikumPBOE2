    private void setupListSelectionListener() {
        javax.swing.event.ListSelectionListener listener = e -> {
            if (!e.getValueIsAdjusting()) {
                int index = jListID.getSelectedIndex();
                if (index == -1) {
                    index = jListName.getSelectedIndex();
                }
                
                if (index != -1) {
                    String id = modelID.getElementAt(index);
                    String nama = modelNama.getElementAt(index);
                    jTextFieldIDEdit.setText(id);
                    jTextFieldNamaEdit.setText(nama);
                    jTextFieldIDDelete.setText(id);
                    jTextFieldNameDelete.setText(nama);
                }
            }
        };
        
        jListID.addListSelectionListener(listener);
        jListName.addListSelectionListener(listener);
        
        jListID.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        jListName.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    }
