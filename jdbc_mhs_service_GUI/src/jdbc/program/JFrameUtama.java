    private void jButtonTambahkanNameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTambahkanNameActionPerformed
        // TODO add your handling code here:
        String nama = jTextFieldName.getText().trim();
        if (nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama tidak boleh kosong!");
            return;
        }
        
        try {
            Mahasiswa mhs = new Mahasiswa(0, nama);
            service.add(mhs);
            
            JOptionPane.showMessageDialog(this, "Data berhasil ditambahkan!");
            refreshListData();
            jTextFieldName.setText("");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal menambah: " + e.getMessage());
        }
        
    }//GEN-LAST:event_jButtonTambahkanNameActionPerformed

    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        // TODO add your handling code here:
        String idStr = jTextFieldIDEdit.getText().trim();
        String nama = jTextFieldNamaEdit.getText().trim();
        
        if (idStr.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "ID dan Nama harus diisi!");
            return;
        }
        
        try {
            int id = Integer.parseInt(idStr);
            Mahasiswa mhs = new Mahasiswa(id, nama);
            service.update(mhs);
            
            JOptionPane.showMessageDialog(this, "Data berhasil diupdate!");
            refreshListData();
            jTextFieldIDEdit.setText("");
            jTextFieldNamaEdit.setText("");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID harus berupa angka!");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal mengupdate: " + e.getMessage());
        }
    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteActionPerformed
        // TODO add your handling code here:
        String idStr = jTextFieldIDDelete.getText().trim();
        
        if (idStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "ID harus diisi!");
            return;
        }
        
        try {
            int id = Integer.parseInt(idStr);
            service.delete(id);
            
            JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
            refreshListData();
            jTextFieldIDDelete.setText("");
            jTextFieldNameDelete.setText("");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID harus berupa angka!");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal menghapus: " + e.getMessage());
        }
    }//GEN-LAST:event_jButtonDeleteActionPerformed

